import { initializeApp } from 'firebase/app';
import { getAuth, GoogleAuthProvider } from 'firebase/auth';
import { getFirestore, doc, getDocFromServer } from 'firebase/firestore';
import firebaseConfig from '../firebase-applet-config.json';

// Filter benign WebChannel fetch stream AbortError noise during iframe reload/cleanup
const originalConsoleError = console.error.bind(console);
console.error = (...args: unknown[]) => {
  const firstArg = args.length > 0 ? String(args[0]) : '';
  const secondArg = args.length > 1 ? String(args[1]) : '';
  if (
    firstArg.includes('AbortError') ||
    secondArg.includes('AbortError') ||
    firstArg.includes('signal is aborted without reason') ||
    secondArg.includes('signal is aborted without reason')
  ) {
    return;
  }
  originalConsoleError(...args);
};

